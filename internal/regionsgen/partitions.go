package regionsgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"

	"github.com/icearp/disco-cli/internal/providers/aws/awsregions"
)

// PartitionsFile is the basename tools/genregions writes the partition table
// to, next to GeneratedFile.
const PartitionsFile = "partitions_generated.go"

// sdkCoreModule is the aws-sdk-go-v2 core module. Its endpoint-rules package
// carries the partition definitions every service client resolves against, so
// the pinned copy is the partition truth disco and the SDK share.
const sdkCoreModule = "github.com/aws/aws-sdk-go-v2"

// partitionsJSONPath is partitions.json relative to the core module root.
var partitionsJSONPath = filepath.Join("internal", "endpoints", "awsrulesfn", "partitions.json")

// partitionsDoc is the subset of partitions.json the table is built from.
type partitionsDoc struct {
	Partitions []struct {
		ID          string                     `json:"id"`
		RegionRegex string                     `json:"regionRegex"`
		Regions     map[string]json.RawMessage `json:"regions"`
		Outputs     struct {
			DNSSuffix            string `json:"dnsSuffix"`
			DualStackDNSSuffix   string `json:"dualStackDnsSuffix"`
			ImplicitGlobalRegion string `json:"implicitGlobalRegion"`
		} `json:"outputs"`
	} `json:"partitions"`
}

// readPartitions reads the partition table from the partitions.json of the
// aws-sdk-go-v2 core module at coreDir. Order follows the file, because the
// SDK's own region-to-partition lookup walks it in that order.
//
// A partition missing its id, regex or DNS suffix is an error, not a skipped
// row: every consumer of the table treats an absent partition as unknown, so
// a silently dropped one would turn a real partition into an unsupported one.
func readPartitions(coreDir string) ([]awsregions.Partition, error) {
	path := filepath.Join(coreDir, partitionsJSONPath)
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("regionsgen: read %s: %w", path, err)
	}
	return parsePartitions(path, src)
}

func parsePartitions(path string, src []byte) ([]awsregions.Partition, error) {
	var doc partitionsDoc
	if err := json.Unmarshal(src, &doc); err != nil {
		return nil, fmt.Errorf("regionsgen: parse %s: %w", path, err)
	}
	if len(doc.Partitions) == 0 {
		return nil, fmt.Errorf("regionsgen: %s lists no partitions; its schema likely changed", path)
	}
	out := make([]awsregions.Partition, 0, len(doc.Partitions))
	for _, p := range doc.Partitions {
		if p.ID == "" || p.RegionRegex == "" || p.Outputs.DNSSuffix == "" {
			return nil, fmt.Errorf("regionsgen: %s: partition %q lacks id, regionRegex or dnsSuffix; its schema likely changed", path, p.ID)
		}
		if _, err := regexp.Compile(p.RegionRegex); err != nil {
			return nil, fmt.Errorf("regionsgen: %s: partition %s regionRegex is not RE2: %w", path, p.ID, err)
		}
		regions := make([]string, 0, len(p.Regions))
		for r := range p.Regions {
			regions = append(regions, r)
		}
		slices.Sort(regions)
		out = append(out, awsregions.Partition{
			ID:                   p.ID,
			RegionRegex:          p.RegionRegex,
			DNSSuffix:            p.Outputs.DNSSuffix,
			DualStackDNSSuffix:   p.Outputs.DualStackDNSSuffix,
			ImplicitGlobalRegion: p.Outputs.ImplicitGlobalRegion,
			Regions:              regions,
		})
	}
	return out, nil
}

// realRegions returns the regions of p a client can be pointed at: the keys of
// its partitions.json regions map that match its own regionRegex. The map also
// carries one global pseudo-region per partition ("aws-global",
// "aws-cn-global", ...), which names an endpoint rather than a region and which
// no regionRegex matches. The result is sorted, as p.Regions is.
func realRegions(p awsregions.Partition) []string {
	re := regexp.MustCompile(p.RegionRegex) // parsePartitions rejected a non-RE2 regex
	var out []string
	for _, r := range p.Regions {
		if re.MatchString(r) {
			out = append(out, r)
		}
	}
	return out
}

// regionsByPartition maps each partition id to its realRegions.
func regionsByPartition(parts []awsregions.Partition) map[string][]string {
	out := make(map[string][]string, len(parts))
	for _, p := range parts {
		out[p.ID] = realRegions(p)
	}
	return out
}

// RenderPartitions formats the partition table, and the region lists derived
// from it, as the source of the generated awsregions file.
func RenderPartitions(parts []awsregions.Partition) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by tools/genregions. DO NOT EDIT.

package awsregions

// Partitions is every partition the pinned aws-sdk-go-v2 knows, copied from its
// internal/endpoints/awsrulesfn/partitions.json in file order. Treat as
// read-only.
var Partitions = []Partition{
`)
	for _, p := range parts {
		buf.WriteString("\t{\n")
		fmt.Fprintf(&buf, "\t\tID: %q,\n", p.ID)
		fmt.Fprintf(&buf, "\t\tRegionRegex: %q,\n", p.RegionRegex)
		fmt.Fprintf(&buf, "\t\tDNSSuffix: %q,\n", p.DNSSuffix)
		fmt.Fprintf(&buf, "\t\tDualStackDNSSuffix: %q,\n", p.DualStackDNSSuffix)
		fmt.Fprintf(&buf, "\t\tImplicitGlobalRegion: %q,\n", p.ImplicitGlobalRegion)
		buf.WriteString("\t\tRegions: []string{\n")
		for _, r := range p.Regions {
			fmt.Fprintf(&buf, "\t\t\t%q,\n", r)
		}
		buf.WriteString("\t\t},\n\t},\n")
	}
	buf.WriteString("}\n")

	byPartition := regionsByPartition(parts)
	var all []string
	owner := map[string]string{}
	buf.WriteString(`
// RegionsByPartition maps each partition id to the regions disco can scan in
// it: the partition's regions from partitions.json, less the global
// pseudo-region ("aws-global", ...) that names an endpoint, not a region.
// --regions all expands to the account's own partition's entry. Treat as
// read-only.
var RegionsByPartition = map[string][]string{
`)
	for _, p := range parts {
		fmt.Fprintf(&buf, "\t%q: {\n", p.ID)
		for _, r := range byPartition[p.ID] {
			// The account's partition is read back from a region, so a region
			// two partitions list would make that lookup ambiguous.
			if first, dup := owner[r]; dup {
				return nil, fmt.Errorf("regionsgen: region %s is listed by partitions %s and %s", r, first, p.ID)
			}
			owner[r] = p.ID
			fmt.Fprintf(&buf, "\t\t%q,\n", r)
			all = append(all, r)
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	slices.Sort(all)
	buf.WriteString(`
// Regions is every partition's RegionsByPartition entry in one sorted list.
// Treat as read-only; callers that expose it clone first.
var Regions = []string{
`)
	for _, r := range all {
		fmt.Fprintf(&buf, "\t%q,\n", r)
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("regionsgen: format generated partitions source: %w", err)
	}
	return formatted, nil
}
